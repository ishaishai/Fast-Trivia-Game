/**
 * Every word in Meridian. Plain verbs, sentence case, a little wry.
 * One action keeps one name: you "enter" a competition and "start the clock".
 */
/** "the Daily" inside a sentence; session names are proper nouns. */
export function inSentence(title: string): string {
  return title.startsWith('The ') ? `the ${title.slice(4)}` : title;
}

